import assert from "node:assert/strict";
import { test } from "node:test";
import { createHash } from "node:crypto";
import { existsSync, readFileSync, readdirSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import lock from "../upstream/lock.json";
import map from "../source-to-port-map.json";
import retained from "../upstream/retained-source.json";
import { catalog, ECOLOGITS_IDENTITY } from "../src/index.js";

const root = fileURLToPath(new URL("../", import.meta.url));
const hash = (path: string) =>
  createHash("sha256")
    .update(readFileSync(`${root}/${path}`))
    .digest("hex");
const snapshot = `upstream/${retained.snapshot_directory}`;

test("EL01/RL04/RL06/RL09: source, package, environment, catalog and license hashes remain pinned", () => {
  assert.equal(retained.source_artifact.sha256, lock.source_artifact.sha256);
  assert.equal(
    hash("upstream/retained-source.json"),
    lock.retained_source_manifest_sha256,
  );
  for (const [path, expected] of Object.entries(lock.files))
    assert.equal(hash(`${snapshot}/${path}`), expected, path);
  assert.equal(hash("oracle/uv.lock"), lock.oracle_lock_sha256);
  assert.equal(hash("data/catalog.json"), lock.catalog_sha256);
  for (const [path, expected] of Object.entries(lock.core_files))
    assert.equal(hash(path), expected, path);
  assert.equal(hash("LICENSE"), lock.files.LICENSE);
  assert.equal(hash("CITATION.cff"), lock.files["CITATION.cff"]);
  assert.equal(catalog.models.length, lock.counts.resolved_models);
  assert.equal(catalog.electricity_mixes.length, lock.counts.electricity_mixes);
  assert.equal(catalog.video.models.length, lock.counts.video_models);
  assert.equal(ECOLOGITS_IDENTITY.catalog_sha256, lock.catalog_sha256);
  assert.equal(
    Object.keys(retained.retained_files).length,
    Object.keys(lock.files).length,
  );
  assert.ok(Object.keys(retained.excluded_files).length > 0);
  assert.equal(
    existsSync(`${root}/upstream/${lock.source_artifact.filename}`),
    false,
  );
  assert.equal(existsSync(`${root}/${snapshot}/tests`), false);
  assert.equal(existsSync(`${root}/${snapshot}/docs`), false);
});

test("Retained-source negative checks: hash, path, allowlist and original-artifact binding failures are rejected", () => {
  const mutations = [
    (value: any) => {
      value.retained_files["LICENSE"].sha256 = "0".repeat(64);
    },
    (value: any) => {
      value.retained_files["LICENSE"].size += 1;
    },
    (value: any) => {
      value.retained_files["../outside"] = value.retained_files.LICENSE;
      delete value.retained_files.LICENSE;
    },
    (value: any) => {
      value.source_artifact.sha256 = "0".repeat(64);
    },
    (value: any) => {
      const excluded = Object.keys(value.excluded_files)[0];
      value.retained_files[excluded] = value.excluded_files[excluded];
      delete value.excluded_files[excluded];
    },
  ];
  for (const mutate of mutations) {
    const manifest = structuredClone(retained);
    mutate(manifest);
    // The locked oracle interpreter, like the other checks here: a bare "python" is missing on
    // Linux hosts that only have python3, and the spawn error then read as a TypeError.
    const run = spawnSync(
      "uv",
      ["run", "--project", "oracle", "--offline", "--frozen", "python", "-X", "utf8", "tools/check_retained_source.py", "--stdin"],
      { cwd: root, input: JSON.stringify(manifest), encoding: "utf8" },
    );
    assert.equal(run.error, undefined);
    assert.notEqual(run.status, 0);
    assert.ok(run.stderr.includes("AssertionError"));
  }
});

