import { existsSync, readFileSync, readdirSync, realpathSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

// Licence notices for the third-party code the website ships. The list comes from the
// dependency graph of apps/web (through the workspace packages it imports), plus the bundler's
// own runtime helpers. The build plugin then checks the real bundle against that list and fails
// when the bundle contains a package the list lacks, so the page cannot silently miss one.

const webRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const GENERATED_NOTICES = resolve(webRoot, "src/generated/website-notices.ts");
const NOTICE_FILE = /^(licen[cs]e|copying|notice)([._-].*)?$/i;
const WORKSPACE_SCOPE = "@footprint/";

function packageManifest(from, name) {
  for (let current = from; ; current = dirname(current)) {
    const candidate = join(current, "node_modules", ...name.split("/"), "package.json");
    if (existsSync(candidate)) return realpathSync(candidate);
    if (dirname(current) === current) throw new Error(`Missing dependency for website notices: ${name}`);
  }
}

const readText = (path) => readFileSync(path, "utf8").replace(/\r\n/g, "\n").trim();

function noticeFiles(directory) {
  return readdirSync(directory)
    .filter((name) => NOTICE_FILE.test(name) && statSync(join(directory, name)).isFile())
    .sort();
}

/**
 * Vite's LICENSE.md also lists the licences of the code bundled into Vite's own Node build.
 * Only Vite core code (the preload helper and module preload polyfill) reaches the website, so
 * the page shows the core section. A changed file layout stops the build for review.
 */
function viteCoreNotice(text) {
  const end = text.indexOf("# Licenses of bundled dependencies");
  if (!text.startsWith("# Vite core license") || end < 0)
    throw new Error("Vite's LICENSE.md layout changed; review the website notice for Vite");
  return text.slice(0, end).trim();
}

function component(manifestPath, extraFiles = []) {
  const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
  const directory = dirname(manifestPath);
  const files = [...noticeFiles(directory), ...extraFiles];
  const notices = files.map((file) => {
    const text = readText(join(directory, file));
    return { file, text: manifest.name === "vite" && file === "LICENSE.md" ? viteCoreNotice(text) : text };
  });
  if (!notices.length) throw new Error(`No licence file in ${manifest.name}@${manifest.version}`);
  return {
    name: manifest.name,
    version: manifest.version,
    license: typeof manifest.license === "string" ? manifest.license : "NOASSERTION",
    notices,
  };
}

/** Every third-party package the website build may ship, with its full licence texts. */
export function websiteComponents(root = webRoot) {
  const found = new Map();
  const visit = (manifestPath) => {
    const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
    const key = `${manifest.name}@${manifest.version}`;
    if (found.has(key)) return;
    const external = !manifest.name.startsWith(WORKSPACE_SCOPE) && manifestPath !== join(root, "package.json");
    found.set(key, external ? component(manifestPath) : null);
    for (const name of Object.keys(manifest.dependencies ?? {}).sort())
      visit(packageManifest(dirname(manifestPath), name));
  };
  visit(join(root, "package.json"));
  // Vite writes its preload helper and module preload polyfill into the entry chunk, and
  // Rolldown its runtime helpers for CommonJS packages such as React.
  const vite = packageManifest(root, "vite");
  const rolldown = packageManifest(dirname(vite), "rolldown");
  for (const item of [component(vite), component(rolldown, ["THIRD-PARTY-LICENSE"])])
    found.set(`${item.name}@${item.version}`, item);
  return [...found.values()]
    .filter(Boolean)
    .sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
}

export function renderNoticesModule(components) {
  return [
    "// Generated by apps/web/scripts/website-notices.mjs from the website's dependencies. Do not edit.",
    "export type WebsiteNotice = { name: string; version: string; license: string; notices: { file: string; text: string }[] };",
    `export const websiteNotices: WebsiteNotice[] = ${JSON.stringify(components, null, 2)};`,
    "",
  ].join("\n");
}

/** Writes the generated module when its content changed. Returns true when it wrote. */
export function writeNoticesModule(root = webRoot, target = GENERATED_NOTICES) {
  const content = renderNoticesModule(websiteComponents(root));
  const current = existsSync(target) ? readFileSync(target, "utf8").replace(/\r\n/g, "\n") : null;
  if (current === content) return false;
  writeFileSync(target, content, "utf8");
  return true;
}

function packageOf(file, cache) {
  const parts = file.split(/[\\/]/);
  const index = parts.lastIndexOf("node_modules");
  if (index < 0) return null;
  const length = parts[index + 1]?.startsWith("@") ? 2 : 1;
  const directory = parts.slice(0, index + 1 + length).join(sep);
  if (!cache.has(directory)) {
    const manifest = JSON.parse(readFileSync(join(directory, "package.json"), "utf8"));
    cache.set(directory, `${manifest.name}@${manifest.version}`);
  }
  return cache.get(directory);
}

/**
 * Packages whose code or files are in a build output: module ids of every chunk and the source
 * files of every emitted asset (fonts). Virtual helper modules are mapped to the bundler package
 * that writes them; any other virtual module is reported so a new helper cannot go unnoticed.
 */
export function shippedPackages(bundle, root = webRoot, helpers = bundlerHelpers(root)) {
  const cache = new Map();
  const packages = new Set();
  const unknown = new Set();
  for (const output of Object.values(bundle)) {
    const files =
      output.type === "chunk"
        ? output.moduleIds
        : (output.originalFileNames ?? []).map((name) => resolve(root, name));
    for (const id of files) {
      if (id.startsWith("\0")) {
        const helper = helpers.find(([pattern]) => pattern.test(id));
        if (helper) packages.add(helper[1]);
        else unknown.add(id.slice(1));
        continue;
      }
      const owner = packageOf(id.split("?")[0], cache);
      if (owner && !owner.startsWith(WORKSPACE_SCOPE)) packages.add(owner);
    }
  }
  return { packages: [...packages].sort(), unknownVirtual: [...unknown].sort() };
}

function bundlerHelpers(root) {
  const read = (path) => {
    const manifest = JSON.parse(readFileSync(path, "utf8"));
    return `${manifest.name}@${manifest.version}`;
  };
  const vite = packageManifest(root, "vite");
  return [
    [/^\0vite\//, read(vite)],
    [/^\0rolldown\/runtime/, read(packageManifest(dirname(vite), "rolldown"))],
  ];
}

/** Regenerates the notices before the build and refuses a bundle with an unlisted package. */
export function websiteNoticesPlugin(root = webRoot) {
  return {
    name: "website-notices",
    apply: "build",
    buildStart() {
      writeNoticesModule(root);
    },
    generateBundle(_options, bundle) {
      const listed = new Set(websiteComponents(root).map((item) => `${item.name}@${item.version}`));
      const { packages, unknownVirtual } = shippedPackages(bundle, root);
      const missing = packages.filter((key) => !listed.has(key));
      if (missing.length)
        this.error(`The website ships packages without licence notices: ${missing.join(", ")}`);
      if (unknownVirtual.length)
        this.error(`The website ships virtual modules of unknown origin: ${unknownVirtual.join(", ")}`);
    },
  };
}
