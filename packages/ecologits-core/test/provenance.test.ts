test("EL23: every mapped source symbol is bound to its exact source hash", () => {
  for (const row of map.functions_and_types) {
    assert.equal(hash(`${snapshot}/${row.upstream_file}`), row.source_sha256);
    assert.ok(row.fixtures.length > 0 || row.disposition === "excluded");
    if (row.disposition === "excluded") assert.ok(row.reason);
  }
  assert.ok(map.functions_and_types.length > 0);
  const run = spawnSync(
    "uv",
    [
      "run",
      "--project",
      "oracle",
      "--offline",
      "--frozen",
      "python",
      "-X",
      "utf8",
      "tools/check_surface.py",
    ],
    { cwd: root, encoding: "utf8" },
  );
  assert.equal(run.status, 0, run.stderr);
});

test("AR01/BE16/EV12: runtime imports only local source/data and has no I/O or capture entry point", () => {
  for (const file of readdirSync(`${root}/src`).filter((path) =>
    path.endsWith(".ts"),
  )) {
    const text = readFileSync(`${root}/src/${file}`, "utf8");
    for (const match of text.matchAll(/(?:from|import)\s*['"]([^'"]+)['"]/g))
      assert.match(match[1], /^\.\.?\//, `${file} import ${match[1]}`);
    assert.doesNotMatch(
      text,
      /\b(?:fetch|XMLHttpRequest|WebSocket|indexedDB|window|document|setInterval|Date\.now|Math\.random)\b/,
      file,
    );
    assert.match(text, /SPDX-License-Identifier: MPL-2.0/, file);
  }
  const identityModule = readFileSync(`${root}/src/identity.ts`, "utf8");
  assert.deepEqual(
    [...identityModule.matchAll(/from\s*['"]([^'"]+)['"]/g)].map(
      (match) => match[1],
    ),
    ["../data/identity.json"],
  );
});
