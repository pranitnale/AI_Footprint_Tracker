const model = (id: string | null) => id as RequestObservation["model_id"] & AttemptObservation["model_id"];

/** A ChatGPT request and its reply; `asked` is the model the request names, `answered` the reply's. */
function chatgpt(asked: string | null, answered: string | null) {
  const [request, attempt] = records();
  const r: RequestObservation = { ...request, site: "chatgpt", model_id: model(asked) };
  const a: AttemptObservation = { ...attempt, model_id: model(answered) };
  return [r, a] as const;
}

/** The saved copy of a live reply, linked to it by the reply key, naming `answered`. */
function savedReply(request: RequestObservation, attempt: AttemptObservation, answered: string): HistoryMessage {
  const answer = attempt.tokens.answer_output;
  return HistoryMessageSchema.parse({
    schema_version: "3.0.0",
    kind: "history_message",
    timing: null,
    message_key: "c".repeat(64),
    role: "response",
    conversation_key: request.conversation_key,
    key_version: "1",
    site: request.site,
    parent_key: "d".repeat(64),
    prompt_key: "d".repeat(64),
    provider_request_key: null,
    provider_attempt_key: attempt.provider_attempt_key,
    occurred_at: attempt.started_at,
    date_basis: "message_created",
    observed_at: attempt.started_at,
    model_id: answered,
    proposed_method_id: packagedMethods.original.method_id,
    proposed_method_hash: packagedMethods.original.method_hash,
    company_dedup_key: null,
    tokens: answer,
    inline_file_text: null,
    parts: historyResponseParts(answer),
    generation: emptyGeneration(),
    text_complete: true,
    coverage_reasons: ["history_only"],
  });
}

test("a request counts for the model that answered it", () => {
  const observer = new BreakdownObserver({}, { bucket: "day", timezone: "UTC" });
  // ChatGPT sends "auto": the request names no model and only its reply does.
  const [auto, autoReply] = chatgpt(null, "chatgpt-gpt-6-sol");
  // Asked for one model, answered by another, then regenerated by a third. The scan can read the
  // later reply first; the request counts once, for its earliest reply.
  const [asked, first] = chatgpt("chatgpt-gpt-5-6-sol", "chatgpt-gpt-6-1-sol");
  const again: AttemptObservation = {
    ...first,
    attempt_id: crypto.randomUUID(),
    started_at: "2026-09-10T10:05:00.000Z",
    model_id: model("chatgpt-gpt-6-astra"),
  };
  // A reply that names no model leaves the request with the model it asked for.
  const [kept, keptReply] = chatgpt("chatgpt-gpt-5-4", null);
  // Neither names a model: the request stays without one.
  const [unnamed, unnamedReply] = chatgpt(null, null);
  for (const request of [auto, asked, kept, unnamed]) observer.request(request);
  observer.attempt(autoReply, auto, undefined);
  observer.attempt(again, asked, undefined);
  observer.attempt(first, asked, undefined);
  observer.attempt(keptReply, kept, undefined);
  observer.attempt(unnamedReply, unnamed, undefined);
  const parts = observer.result();
  assert.deepEqual(
    Object.fromEntries(Object.entries(parts.models).map(([id, part]) => [id, [part.requests, part.attempts]])),
    {
      "chatgpt-gpt-6-sol": [1, 1],
      "chatgpt-gpt-6-1-sol": [1, 1],
      "chatgpt-gpt-6-astra": [0, 1],
      "chatgpt-gpt-5-4": [1, 1],
    },
  );
  assert.equal(parts.sites.chatgpt!.requests, 4);
  // The model that was asked for but answered nothing gets no empty part, and a second read adds nothing.
  assert.equal(parts.models["chatgpt-gpt-5-6-sol"], undefined);
  assert.equal(observer.result().models["chatgpt-gpt-6-sol"]!.requests, 1);
});

test("a reply recorded live without a model counts for the model its saved copy names", () => {
  // Early October 2026 ChatGPT captures ended unread: the request ("auto") and the live reply
  // name no model, while the saved reply linked to it names the model that answered.
  const [request, attempt] = chatgpt(null, null);
  const reply: AttemptObservation = {
    ...attempt,
    state: "interrupted_unconfirmed",
    provider_attempt_key: "e".repeat(64),
  };
  const saved = savedReply(request, reply, "chatgpt-gpt-5-4");
  // The live reply asked for one model and its saved copy names the one that answered.
  const [askedRequest, askedAttempt] = chatgpt("chatgpt-gpt-6-sol", null);
  const askedReply: AttemptObservation = {
    ...askedAttempt,
    model_id: model("chatgpt-gpt-6-sol"),
    model_evidence: "request_field",
    provider_attempt_key: "f".repeat(64),
  };
  const askedSaved = savedReply(askedRequest, askedReply, "chatgpt-gpt-6-astra");
  const split = (calculationView: "original" | "recalculated") => {
    const observer = new BreakdownObserver({ calculationView }, { bucket: "day", timezone: "UTC" });
    observer.request(request);
    observer.request(askedRequest);
    observer.attempt(reply, request, undefined, undefined, saved);
    observer.attempt(askedReply, askedRequest, undefined, undefined, askedSaved);
    const parts = observer.result();
    return {
      models: Object.fromEntries(Object.entries(parts.models).map(([id, part]) => [id, [part.requests, part.attempts]])),
      requests: parts.sites.chatgpt!.requests,
      sites: parts.modelSites,
    };
  };
  // EcoLogits estimates each linked reply for linkedReplyModel, so the split follows it.
  assert.deepEqual(split("recalculated"), {
    models: { "chatgpt-gpt-5-4": [1, 1], "chatgpt-gpt-6-astra": [1, 1] },
    requests: 2,
    sites: { "chatgpt-gpt-5-4": "chatgpt", "chatgpt-gpt-6-astra": "chatgpt" },
  });
  // The original view keeps the live models, as its token sums do.
  assert.deepEqual(split("original"), {
    models: { "chatgpt-gpt-6-sol": [1, 1] },
    requests: 2,
    sites: { "chatgpt-gpt-6-sol": "chatgpt" },
  });
});

const observed = (value: number): TokenMeasurement => ({
  value: String(value),
  evidence: "heuristic_estimate",
  scope: "observed_text",
  completeness: "complete_for_scope",
  profile_id: "o200k-base-4.0.0-reference",
  reason: "tokenizer_mapping_unverified",
});

test("an unread live reply and its saved copy count once, for the saved model, through usageBreakdown", async () => {
  const now = new Date("2026-10-12T10:30:00.000Z");
  // An empty profile: the packaged coordinator, EcoLogits by default, with no records yet.
  const profile = await largeProfile({
    size: { chats: 1, requests: 0, historyChats: 0, historyTurns: 1, days: 1, erasedRequests: 0, erasedDay: false },
    mode: "personal",
    seed: 808,
    now,
  });
  try {
    const executor = createLocalExecutor();
    const conversation = "1".repeat(64);
    const at = "2026-10-05T09:00:00.000Z";
    const ended = "2026-10-05T09:00:20.000Z";
    const answer = observed(240);
    // The live capture of early October 2026: ChatGPT "auto" names no model, and the reply
    // ended unread, so it names none either.
    const [base, baseAttempt] = records();
    const request: RequestObservation = {
      ...base,
      site: "chatgpt",
      conversation_key: conversation,
      provider_request_key: "2".repeat(64),
      dispatched_at: at,
      ended_at: ended,
      state: "interrupted_unconfirmed",
    };
    const tokens = { ...baseAttempt.tokens, new_input_text: observed(12), answer_output: answer };
    const attempt: AttemptObservation = {
      ...baseAttempt,
      request_id: request.request_id,
      provider_attempt_key: "3".repeat(64),
      started_at: at,
      ended_at: ended,
      state: "interrupted_unconfirmed",
      tokens: { ...tokens, output_total: composeOutputTotal(tokens) },
      tokenizer_profile_id: "o200k-base-4.0.0-reference",
      proposed_method_id: packagedMethods.original.method_id,
    };
    // Saved as a finished capture is, the way largeProfile saves its live records.
    const envelope = await executor.estimate({ family: "live", request, attempt });
    const estimate =
      envelope.requested_method.engine_id === "original" && envelope.raw?.engine_id === "original" && !Array.isArray(envelope.raw.result)
        ? envelope.raw.result
        : envelope;
    await profile.repository.commitCapture({
      scope: profile.scope,
      observations: [request, attempt],
      originals: [envelope],
      archivedEstimates: [estimate as any],
      currentEstimate: { attemptId: attempt.attempt_id, estimate: estimate as any },
    });
    // The saved chat names the model that answered and links to the live request and reply by
    // their keys.
    const common = {
      schema_version: "3.0.0",
      kind: "history_message",
      timing: null,
      conversation_key: conversation,
      key_version: "1",
      site: "chatgpt",
      date_basis: "message_created",
      observed_at: now.toISOString(),
      proposed_method_id: packagedMethods.original.method_id,
      proposed_method_hash: packagedMethods.original.method_hash,
      company_dedup_key: null,
      inline_file_text: null,
      generation: emptyGeneration(),
      text_complete: true,
      coverage_reasons: ["history_only"],
    };
    const prompt = HistoryMessageSchema.parse({
      ...common,
      message_key: "4".repeat(64),
      role: "prompt",
      parent_key: null,
      prompt_key: null,
      provider_request_key: request.provider_request_key,
      provider_attempt_key: null,
      occurred_at: at,
      model_id: null,
      tokens: observed(12),
      parts: null,
    });
    const reply = HistoryMessageSchema.parse({
      ...common,
      message_key: "5".repeat(64),
      role: "response",
      parent_key: prompt.message_key,
      prompt_key: prompt.message_key,
      provider_request_key: null,
      provider_attempt_key: attempt.provider_attempt_key,
      occurred_at: "2026-10-05T09:00:01.000Z",
      model_id: "chatgpt-gpt-5-5",
      tokens: answer,
      parts: historyResponseParts(answer),
    });
    const page = HistoryPageSchema.parse({
      schema_version: "3.0.0",
      site: "chatgpt",
      conversation_key: conversation,
      observed_at: now.toISOString(),
      deletion_epoch: 0,
      branch_scope: "loaded_messages",
      selected_leaf_key: null,
      branch_message_keys: null,
      root_message_key: prompt.message_key,
      first_request_verified: true,
      has_earlier: false,
      has_later: false,
      messages: [prompt, reply],
    });
    const snapshot = await profile.db.publicationSnapshot(profile.scope.namespace);
    await profile.db.commitHistory(
      profile.scope,
      page,
      {
        authority: historyAuthority(snapshot),
        erasureVersion: snapshot.erasureVersion,
        estimates: Object.fromEntries(page.messages.map((m) => [m.message_key, estimateHistoricalText(m)])),
        envelopes: { [reply.message_key]: await executor.estimate({ family: "history", record: reply }) },
      },
      () => true,
    );
    await settleRecalculation(profile.coordinator);
    const view = await profile.coordinator.usageBreakdown({ bucket: "day", timezone: "UTC" });
    assert.equal(view.calculation.view, "recalculated");
    // Counted once, live: the saved prompt and reply are matched and add no request.
    assert.equal(view.total.requests, 1);
    assert.equal(view.history?.total.prompt_count, "0");
    assert.equal(view.history?.total.matched_live_message_count, "2");
    const energy = view.total.metrics.energy;
    assert.equal(energy.known, 1, "the reply is estimated with its saved copy");
    // The request, its reply and its figures belong to the model the saved reply names.
    const part = view.models["chatgpt-gpt-5-5"];
    assert.ok(part, "the saved model has the live request");
    assert.deepEqual([part.requests, part.attempts, part.metrics.energy.value], [1, 1, energy.value]);
    assert.deepEqual(part.selections.map((s) => s.replies), [1]);
    assert.deepEqual(Object.keys(view.models), ["chatgpt-gpt-5-5"]);
    assert.equal(view.modelSites["chatgpt-gpt-5-5"], "chatgpt");
  } finally {
    profile.close();
  }
});

test("a saved ChatGPT prompt counts for the model of the reply under it, also without a prompt key", async () => {
  // Live QA of 19 October 2026: 18 saved ChatGPT prompts showed "without a named model". 13 of
  // them had replies naming chatgpt-gpt-5-4 with no prompt_key (the prompt and reply carried no
  // shared request id) whose parent_key is the prompt; others had neither key.
  const now = new Date("2026-10-12T10:30:00.000Z");
  const profile = await largeProfile({
    size: { chats: 1, requests: 0, historyChats: 0, historyTurns: 1, days: 1, erasedRequests: 0, erasedDay: false },
    mode: "personal",
    seed: 909,
    now,
  });
  try {
    const executor = createLocalExecutor();
    const conversation = "6".repeat(64);
    const common = {
      schema_version: "3.0.0",
      kind: "history_message",
      timing: null,
      conversation_key: conversation,
      key_version: "1",
      site: "chatgpt",
      date_basis: "message_created",
      observed_at: now.toISOString(),
      proposed_method_id: packagedMethods.original.method_id,
      proposed_method_hash: packagedMethods.original.method_hash,
      company_dedup_key: null,
      inline_file_text: null,
      generation: emptyGeneration(),
      text_complete: true,
      coverage_reasons: ["history_only"],
      provider_request_key: null,
      provider_attempt_key: null,
    };
    const answer = observed(200);
    /** One saved turn; the reply names its prompt by prompt_key, by parent_key, or not at all. */
    const turn = (n: number, model: string, link: "prompt_key" | "parent_key" | "none") => {
      const prompt = HistoryMessageSchema.parse({
        ...common,
        message_key: `${n}a`.padEnd(64, "0"),
        role: "prompt",
        parent_key: null,
        prompt_key: null,
        occurred_at: `2026-10-05T0${n}:00:00.000Z`,
        model_id: null,
        tokens: observed(10),
        parts: null,
      });
      const reply = HistoryMessageSchema.parse({
        ...common,
        message_key: `${n}b`.padEnd(64, "0"),
        role: "response",
        parent_key: link === "parent_key" ? prompt.message_key : null,
        prompt_key: link === "prompt_key" ? prompt.message_key : null,
        occurred_at: `2026-10-05T0${n}:00:01.000Z`,
        model_id: model,
        tokens: answer,
        parts: historyResponseParts(answer),
      });
      return [prompt, reply];
    };
    const messages = [
      ...turn(1, "chatgpt-gpt-5-4", "parent_key"),
      ...turn(2, "chatgpt-gpt-6-sol", "prompt_key"),
      ...turn(3, "chatgpt-gpt-6-astra", "none"),
    ];
    const page = HistoryPageSchema.parse({
      schema_version: "3.0.0",
      site: "chatgpt",
      conversation_key: conversation,
      observed_at: now.toISOString(),
      deletion_epoch: 0,
      branch_scope: "loaded_messages",
      selected_leaf_key: null,
      branch_message_keys: null,
      root_message_key: messages[0]!.message_key,
      first_request_verified: true,
      has_earlier: false,
      has_later: false,
      messages,
    });
    const envelopes: Record<string, unknown> = {};
    for (const m of messages)
      if (m.role === "response") envelopes[m.message_key] = await executor.estimate({ family: "history", record: m });
    const snapshot = await profile.db.publicationSnapshot(profile.scope.namespace);
    await profile.db.commitHistory(
      profile.scope,
      page,
      {
        authority: historyAuthority(snapshot),
        erasureVersion: snapshot.erasureVersion,
        estimates: Object.fromEntries(messages.map((m) => [m.message_key, estimateHistoricalText(m)])),
        envelopes: envelopes as any,
      },
      () => true,
    );
    await settleRecalculation(profile.coordinator);
    const view = await profile.coordinator.usageBreakdown({ bucket: "day", timezone: "UTC" });
    const saved = view.history!;
    // The totals are the saved chat's own: three requests and three replies, once each.
    assert.equal(saved.total.prompt_count, "3");
    assert.equal(saved.total.response_count, "3");
    assert.equal(saved.sites.chatgpt!.prompt_count, "3");
    const split = Object.fromEntries(
      Object.entries(saved.models).map(([id, part]) => [id, [part.prompt_count, part.response_count]]),
    );
    // A prompt with no link to its reply stays without a named model; no prompt counts twice.
    assert.deepEqual(split, {
      "chatgpt-gpt-5-4": ["1", "1"],
      "chatgpt-gpt-6-sol": ["1", "1"],
      "chatgpt-gpt-6-astra": ["0", "1"],
    });
  } finally {
    profile.close();
  }
});
